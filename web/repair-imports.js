/* Byte-preserving, latest-request-wins report loading. No candidate code runs here. */
(function (root) {
  'use strict';
  const MAX_BYTES = 8 * 1024 * 1024;
  function decode(bytes, name) {
    if (!(bytes instanceof Uint8Array)) throw new Error('Expected report bytes.');
    if (bytes.byteLength > MAX_BYTES) throw new Error('Choose a report smaller than 8 MiB.');
    let text, report;
    try { text = new TextDecoder('utf-8', { fatal: true }).decode(bytes); }
    catch { throw new Error('Use a UTF-8 JSON report generated by the regression kit.'); }
    try { report = JSON.parse(text); }
    catch { throw new Error('This file is not valid JSON. Choose a report generated by the regression kit.'); }
    const model = root.ProposalData.create(report);
    return { bytes: bytes.slice(), text, model, name };
  }
  function createLoader(commit) {
    let version = 0;
    return Object.freeze({
      cancel() { version += 1; },
      async load(file) {
        const request = ++version;
        try {
          if (file.size > MAX_BYTES) throw new Error('Choose a report smaller than 8 MiB.');
          const buffer = await file.arrayBuffer();
          if (request !== version) return { status: 'superseded' };
          const entry = decode(new Uint8Array(buffer), file.name);
          // Rendering is synchronous. A failed commit must roll back at the UI boundary.
          commit(entry);
          return { status: 'accepted', entry };
        } catch (error) {
          return request === version ? { status: 'rejected', error } : { status: 'superseded' };
        }
      }
    });
  }
  root.RepairImports = Object.freeze({ decode, createLoader, MAX_BYTES });
})(typeof window !== 'undefined' ? window : globalThis);
